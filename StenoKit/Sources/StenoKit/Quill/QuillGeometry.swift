    /// The transform that fits `viewBox` into `rect`, centred, preserving aspect ratio.
    public static func fitting(_ viewBox: CGRect, into rect: CGRect) -> CGAffineTransform {
        guard viewBox.width > 0, viewBox.height > 0 else { return .identity }
        let scale = min(rect.width / viewBox.width, rect.height / viewBox.height)
        let offsetX = rect.minX + (rect.width - viewBox.width * scale) / 2 - viewBox.minX * scale
        let offsetY = rect.minY + (rect.height - viewBox.height * scale) / 2 - viewBox.minY * scale
        return CGAffineTransform(a: scale, b: 0, c: 0, d: scale, tx: offsetX, ty: offsetY)
    }

    /// A closed polygon path through `points` with `transform` applied.
    public static func path(_ points: [CGPoint], transform: CGAffineTransform) -> CGPath {
        let path = CGMutablePath()
        guard let first = points.first else { return path }
        path.move(to: first, transform: transform)
        for point in points.dropFirst() {
            path.addLine(to: point, transform: transform)
        }
        path.closeSubpath()
        return path
    }

    /// Parses the M/L/Z outline data used by the quill drawings.
    static func polygon(from data: String) -> [CGPoint] {
        var points: [CGPoint] = []
        for token in data.split(whereSeparator: { $0 == " " || $0 == "\n" }) {
            var body = Substring(token)
            if let first = body.first, first.isLetter { body = body.dropFirst() }
            if body.last == "Z" { body = body.dropLast() }
            let parts = body.split(separator: ",")
            guard parts.count == 2, let x = Double(parts[0]), let y = Double(parts[1]) else { continue }
            let point = CGPoint(x: x, y: y)
            if points.last != point { points.append(point) }
        }
        return points
    }
